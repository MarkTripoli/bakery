/**
 * Builds the one file `npx <origin>/v1/worker/link.tgz` runs (#70): the
 * worker bootstrap (packages/worker-bootstrap, node: APIs only) bundled by
 * `deno bundle` into one ES module that runs under Node, written as a string
 * the server packs into an npm tarball. The source digest lets a unit test
 * see a stale bundle without running the bundler.
 *
 *   deno run --allow-read --allow-write --allow-run=deno scripts/generate-worker-link-bundle.ts [--check]
 */
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const SOURCE = join(ROOT, "packages/worker-bootstrap/src");
const OUTPUT = join(ROOT, "packages/worker-bootstrap/generated/link-bundle.ts");

export async function workerBootstrapSourceDigest(
  root = ROOT,
): Promise<string> {
  const directory = join(root, "packages/worker-bootstrap/src");
  const names = (await readdir(directory)).filter((name) =>
    name.endsWith(".ts")
  )
    .sort();
  const hash = createHash("sha256");
  for (const name of names) {
    hash.update(name);
    hash.update("\0");
    hash.update(await readFile(join(directory, name)));
    hash.update("\0");
  }
  return hash.digest("hex");
}

async function bundle(): Promise<string> {
  const output = await new Deno.Command("deno", {
    args: ["bundle", "--quiet", join(SOURCE, "bin.ts")],
    cwd: ROOT,
    stdout: "piped",
    stderr: "inherit",
  }).output();
  if (!output.success) throw new Error("deno bundle failed");
  return new TextDecoder().decode(output.stdout);
}

if (import.meta.main) {
  const text = [
    "// Generated by scripts/generate-worker-link-bundle.ts from",
    "// packages/worker-bootstrap/src. Do not edit by hand; run",
    "// `pnpm worker-link:generate`.",
    `export const WORKER_LINK_SOURCE_DIGEST = ${
      JSON.stringify(await workerBootstrapSourceDigest())
    };`,
    `export const WORKER_LINK_BIN = ${
      JSON.stringify("#!/usr/bin/env node\n" + await bundle())
    };`,
    "",
  ].join("\n");
  if (Deno.args.includes("--check")) {
    const current = await readFile(OUTPUT, "utf8").catch(() => "");
    if (current !== text) {
      console.error(
        "worker link bundle is stale: run pnpm worker-link:generate",
      );
      Deno.exit(1);
    }
  } else {
    await writeFile(OUTPUT, text);
  }
}
