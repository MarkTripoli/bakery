function artifactConstants(): string {
  return [
    "/** Maximum bytes accepted in a published artifact content field. */",
    `export const MAX_ARTIFACT_BYTES = ${
      workerArtifactFieldMaxBytes("content")
    };`,
    "/** Maximum bytes accepted in published artifact metadata. */",
    `export const MAX_ARTIFACT_METADATA_BYTES = ${
      workerArtifactFieldMaxBytes("metadata")
    };`,
    "/** Maximum nesting depth accepted in published artifact metadata. */",
    `export const MAX_ARTIFACT_METADATA_DEPTH = ${
      workerArtifactFieldMaxDepth("metadata")
    };`,
    "",
  ].join("\n");
}

/** "Developer+source read" -> "DeveloperAndSourceRead". */
function accessPolicyKey(policy: string): string {
  return policy
    .replace(/\+/g, " and ")
    .replace(/[^A-Za-z0-9]+/g, " ")
    .trim()
    .split(" ")
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join("");
}

function accessConstants(): string {
  const entries = new Map<string, string>();
  for (const policy of [...catalog.accessPolicies].sort()) {
    const key = accessPolicyKey(policy);
    if (entries.has(key)) {
      throw new Error(`access policy key collision: ${key}`);
    }
    entries.set(key, policy);
  }
  const lines = [...entries].map(([key, policy]) =>
    `    ${key}: ${JSON.stringify(policy)},`
  );
  return [
    "/** Every catalog access policy, keyed by an identifier-safe name. */",
    "export const CatalogAccess = Object.freeze(",
    "  {",
    ...lines,
    "  } as const,",
    ");",
    "",
  ].join("\n");
}

export function renderCatalogLiterals(): string {
  const actions = catalog.actions;
  return [
    "// Generated by scripts/generate-catalog-literals.ts from",
    "// docs/technical-design/api-catalog.json and transport-schemas.json.",
    "// Do not edit by hand; run `pnpm catalog:literals`.",
    "",
    union("CatalogActionName", actions.map(({ action }) => action)),
    union(
      "CatalogPermissionKey",
      actions.flatMap(({ permission }) =>
        permission === null ? [] : [permission]
      ),
    ),
    union("CatalogAccessPolicy", catalog.accessPolicies),
    accessConstants(),
    artifactConstants(),
    union("ContractInputName", [
      ...actions.map(({ input }) => input),
      ...Object.keys(transport.inputs),
    ]),
    union("ContractOutputName", [
      ...actions.map(({ output }) => output),
      ...Object.keys(transport.outputs),
    ]),
  ].join("\n");
}

/**
 * Deno's `with { type: "json" }` import attribute widens every literal in
 * transport-schemas.json (enum strings, field names, bounds) to its general
 * type (`string`, `number`, ...), because the checker types a JSON module as
 * an ordinary mutable value rather than a `const`. The contract type
 * machinery in contracts.ts depends on those literals surviving into
 * `typeof transportSchemas.inputs`/`.outputs`. This renders the same JSON as
 * a plain TypeScript module so `as const` preserves them exactly; it is a
 * deep structural copy of the canonical source, not a second schema.
 */
export function renderTransportSchemasModule(): string {
  return [
    "// Generated by scripts/generate-catalog-literals.ts from",
    "// docs/technical-design/transport-schemas.json.",
    "// Do not edit by hand; run `pnpm catalog:literals`.",
    "//",
    "// A deep `as const` mirror of the canonical JSON. Deno's",
    '// `with { type: "json" }` import widens field literals (enum strings,',
    "// names, bounds) to their general type, which defeats the field-level",
    "// literal inference the contract type machinery in contracts.ts",
    "// depends on. Plain TypeScript module source lets `as const` preserve",
    "// those literals exactly.",
    "",
    `const transportSchemas = ${JSON.stringify(transport, null, 2)} as const;`,
    "",
    "export default transportSchemas;",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const rendered = renderCatalogLiterals();
  const renderedTransportModule = renderTransportSchemasModule();
  if (Deno.args.includes("--check")) {
    const current = await Deno.readTextFile(CATALOG_LITERALS_PATH);
    if (current !== rendered) {
      console.error(
        `${CATALOG_LITERALS_PATH} is stale; run pnpm catalog:literals`,
      );
      Deno.exit(1);
    }
    const currentModule = await Deno.readTextFile(
      TRANSPORT_SCHEMAS_MODULE_PATH,
    );
    if (currentModule !== renderedTransportModule) {
      console.error(
        `${TRANSPORT_SCHEMAS_MODULE_PATH} is stale; run pnpm catalog:literals`,
      );
      Deno.exit(1);
    }
  } else {
    await Deno.writeTextFile(CATALOG_LITERALS_PATH, rendered);
    await Deno.mkdir("packages/contracts/generated", { recursive: true });
    await Deno.writeTextFile(
      TRANSPORT_SCHEMAS_MODULE_PATH,
      renderedTransportModule,
    );
  }
}
