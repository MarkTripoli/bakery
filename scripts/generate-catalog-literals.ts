import catalog from "../docs/technical-design/api-catalog.json" with {
  type: "json",
};
import transport from "../docs/technical-design/transport-schemas.json" with {
  type: "json",
};

export const CATALOG_LITERALS_PATH =
  "packages/contracts/src/catalog-literals.ts";
export const TRANSPORT_SCHEMAS_MODULE_PATH =
  "packages/contracts/generated/transport-schemas.ts";

function union(name: string, values: Iterable<string>): string {
  const members = [...new Set(values)].sort().map((value) =>
    `  | ${JSON.stringify(value)}`
  );
  return `export type ${name} =\n${members.join("\n")};\n`;
}

function record(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** Read a WorkerArtifact byte bound from the canonical transport inventory. */
function workerArtifactFieldMaxBytes(fieldName: string): number {
  const inputs = transport.inputs as unknown as Record<string, unknown>;
  const definition = inputs.WorkerArtifact;
  if (!record(definition) || !Array.isArray(definition.fields)) {
    throw new Error("WorkerArtifact input must declare fields");
  }
  const field = definition.fields.find((candidate) =>
    record(candidate) && candidate.name === fieldName
  );
  const bounds = record(field?.bounds) ? field.bounds : undefined;
  const maxBytes = bounds?.maxBytes;
  if (
    typeof maxBytes !== "number" || !Number.isSafeInteger(maxBytes) ||
    maxBytes <= 0
  ) {
    throw new Error(
      `WorkerArtifact.${fieldName} must declare a positive maxBytes`,
    );
  }
  return maxBytes;
}

