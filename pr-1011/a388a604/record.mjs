import { createRequire } from "node:module";
import { writeFileSync, mkdirSync } from "node:fs";
const require = createRequire("/home/marktripoli/Development/bakery-wt/rig-70-s5/apps/web/package.json");
const { chromium } = require("@playwright/test");
const base = "http://127.0.0.1:41871";
const out = "/home/marktripoli/Development/bakery-wt/_notes/pr996-999-stills/stack70/rec";
mkdirSync(out, { recursive: true });
const log = [];
const t0 = Date.now();
const note = (event, extra = {}) => log.push({ at: ((Date.now() - t0) / 1000).toFixed(1), event, ...extra });
const browser = await chromium.launch();
const signin = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const sp = await signin.newPage();
await sp.goto(base + "/sign-in");
await sp.getByLabel("Email").fill("admin70@example.test");
await sp.getByLabel("Password", { exact: true }).fill("Machine-Admin-Passw0rd-1");
await sp.getByRole("button", { name: "Sign in", exact: true }).click();
await sp.waitForURL((url) => !url.pathname.startsWith("/sign-in"), { timeout: 30000 });
const state = await signin.storageState();
await signin.close();
const context = await browser.newContext({
  viewport: { width: 1440, height: 900 },
  storageState: state,
  recordVideo: { dir: out, size: { width: 1440, height: 900 } },
});
const page = await context.newPage();
page.on("response", async (response) => {
  const request = response.request();
  const url = new URL(response.url());
  if (request.method() === "PATCH" && /\/workers\//.test(url.pathname)) note("mode change", { status: response.status(), sent: request.postData() });
  if (request.method() === "POST" && /\/workers\/[^/]+\/revoke/.test(url.pathname)) note("retire", { status: response.status() });
});
await page.goto(base + "/machines");
const open = page.getByRole("link", { name: /build-host-01/ }).first();
await open.waitFor({ timeout: 30000 });
note("fleet list", { badges: await page.locator("[data-ui-component=badge]").allInnerTexts() });
await page.waitForTimeout(2000);
await page.screenshot({ path: out + "/1-fleet-list.png" });
await open.click();
await page.getByRole("heading", { name: "build-host-01" }).waitFor({ timeout: 30000 });
await page.waitForTimeout(1500);
await page.getByRole("button", { name: "Retire this machine" }).first().click();
const dialog = page.getByRole("alertdialog");
await dialog.waitFor();
note("retire dialog", { buttons: await dialog.getByRole("button").allInnerTexts() });
await page.waitForTimeout(2500);
await page.screenshot({ path: out + "/2-retire-dialog.png" });
await dialog.getByRole("button", { name: "Finish and stop instead" }).click();
const banner = page.getByTestId("machine-problem-banner").filter({ hasText: "stops once its current work is done" });
await banner.waitFor({ timeout: 30000 });
note("finishing", { banner: (await banner.innerText()).replace(/\s+/g, " "), segment: await page.getByRole("radio", { name: "Finish and stop" }).isChecked() });
await page.waitForTimeout(2500);
await page.screenshot({ path: out + "/3-finishing.png" });
await page.getByRole("button", { name: "Retire this machine" }).first().click();
await page.getByRole("alertdialog").waitFor();
await page.waitForTimeout(1500);
await page.getByRole("alertdialog").getByRole("button", { name: "Retire now" }).click();
await page.getByTestId("machine-problem-banner").filter({ hasText: "It no longer takes work." }).waitFor({ timeout: 30000 });
note("retired", { banner: (await page.getByTestId("machine-problem-banner").innerText()).replace(/\s+/g, " ") });
await page.waitForTimeout(2500);
await page.screenshot({ path: out + "/4-retired.png" });
await page.goto(base + "/machines");
await page.getByText("Retired", { exact: true }).first().waitFor({ timeout: 30000 });
note("fleet list after", { badges: await page.locator("[data-ui-component=badge]").allInnerTexts() });
await page.waitForTimeout(2000);
await page.screenshot({ path: out + "/5-fleet-after.png" });
const video = await page.video().path();
await context.close();
await browser.close();
writeFileSync(out + "/transcript.json", JSON.stringify(log, null, 2));
console.log(JSON.stringify({ video, log }, null, 2));
