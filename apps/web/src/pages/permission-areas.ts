/** The verbs after the colon of a key; the sentence is `settings.roles.verb.<verb>`. */
export const PERMISSION_VERBS = [
  "read",
  "write",
  "manage",
  "create",
  "decide",
  "export",
  "control",
  "merge",
  "promote",
  "access",
  "invoke",
  "reconcile",
  "respond",
  "accept",
  "readSelf",
  "readPinned",
  "preview",
  "share",
  "author",
  "register",
] as const;
export type PermissionVerb = (typeof PERMISSION_VERBS)[number];

export function isResource(value: string): value is PermissionResource {
  return Object.hasOwn(RESOURCE_AREAS, value);
}

export function isVerb(value: string): value is PermissionVerb {
  return (PERMISSION_VERBS as readonly string[]).includes(value);
}
