// Derives the dark phone Machines detail source from the approved light one.
//
// Paper K-0 has no dark detail phone frame. Its approved light/dark list pairs
// (8SE-0/AD7-0 phone, 8SD-0/A8Y-0 desktop) differ by colour token only, so the
// light-to-dark token map is recomputed here from those four committed exports
// and applied to the light detail phone export 90D-0. Nothing is hand-edited:
// the output is a pure function of the input bytes.
//
//   node scripts/derive-worker-dark-source.mjs --write
//   node scripts/derive-worker-dark-source.mjs --check
//
// --check regenerates in memory and fails unless the committed output is
// byte-identical. Both modes fail when a light token maps to more than one
// dark token, when a pair's token counts differ, or when 90D-0 carries a
// colour token the map does not cover.
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const k0 = "docs/technical-design/worker-readiness/source";

export const PAIRS = [
  [
    `${k0}/list-light-mobile-8SE-0.react-css.txt`,
    `${k0}/list-dark-mobile-AD7-0.react-css.txt`,
  ],
  [
    `${k0}/list-light-desktop-8SD-0.react-css.txt`,
    `${k0}/list-dark-desktop-A8Y-0.react-css.txt`,
  ],
];
export const LIGHT_SOURCE = `${k0}/detail-light-phone-90D-0.react-css.txt`;
export const DERIVED_SOURCE =
  "docs/technical-design/worker-dark-mocks/source/detail-dark-phone-90D-0-derived.react-css.txt";

// A CSS custom property reference or a hex colour literal.
const TOKEN = /var\(--[A-Za-z0-9-]+\)|#[0-9A-Fa-f]{3,8}(?![0-9A-Za-z])/g;
const isColour = (token) =>
  token.startsWith("#") || token.startsWith("var(--color-");
// Fully transparent hex has no theme; it is the same in light and dark.
const isTransparent = (token) => /^#[0-9A-Fa-f]{6}00$/.test(token);

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
const read = (path) => readFile(join(root, path));

export function alignTokenMap(pairs) {
  const map = new Map();
  const issues = [];
  for (const { lightPath, darkPath, light, dark } of pairs) {
    const lightTokens = light.match(TOKEN) ?? [];
    const darkTokens = dark.match(TOKEN) ?? [];
    if (lightTokens.length !== darkTokens.length) {
      issues.push(
        `${lightPath} has ${lightTokens.length} tokens, ${darkPath} has ${darkTokens.length}`,
      );
      continue;
    }
    lightTokens.forEach((token, index) => {
      const targets = map.get(token) ?? new Set();
      targets.add(darkTokens[index]);
      map.set(token, targets);
    });
  }
  for (const [token, targets] of map) {
    if (targets.size !== 1) {
      issues.push(`${token} maps to ${[...targets].join(", ")}`);
    }
  }
  if (issues.length) throw new Error(issues.join("\n"));
  return new Map(
    [...map].sort(([left], [right]) => left < right ? -1 : 1).map((
      [token, targets],
    ) => [token, [...targets][0]]),
  );
}

export async function deriveDarkSource() {
  const pairs = await Promise.all(PAIRS.map(async ([lightPath, darkPath]) => ({
    lightPath,
    darkPath,
    light: (await read(lightPath)).toString("utf8"),
    dark: (await read(darkPath)).toString("utf8"),
  })));
  const map = alignTokenMap(pairs);
  const lightBytes = await read(LIGHT_SOURCE);
  const light = lightBytes.toString("utf8");
  const uncovered = [
    ...new Set(
      (light.match(TOKEN) ?? []).filter((token) =>
        isColour(token) && !isTransparent(token) && !map.has(token)
      ),
    ),
  ];
  if (uncovered.length) {
    throw new Error(
      `${LIGHT_SOURCE} uses colour tokens the map does not cover: ${
        uncovered.join(", ")
      }`,
    );
  }
  const inputs = [...PAIRS.flat(), LIGHT_SOURCE];
  const hashes = await Promise.all(
    inputs.map(async (path) => [path, sha256(await read(path))]),
  );
  const changed = [...map].filter(([from, to]) => from !== to);
  const header = [
    "/**",
    " * DERIVED, not a Paper export. No dark detail phone frame exists in Paper K-0.",
    " * Generated by packages/ui/scripts/derive-worker-dark-source.mjs; do not edit.",
    ` * Light source: ${LIGHT_SOURCE}`,
    " * Token map: aligned token by token from the approved K-0 light/dark pairs",
    " * 8SE-0/AD7-0 (phone) and 8SD-0/A8Y-0 (desktop); every light token maps to",
    " * exactly one dark token. Unlisted tokens (fonts, radii, text sizes,",
    " * transparent) are theme-invariant and kept.",
    " * Inputs (sha256):",
    ...hashes.map(([path, hash]) => ` *   ${hash}  ${path}`),
    " * Map:",
    ...changed.map(([from, to]) => ` *   ${from} -> ${to}`),
    " */",
    "",
  ].join("\n");
  const body = light.replace(TOKEN, (token) => map.get(token) ?? token);
  return {
    map,
    hashes: Object.fromEntries(hashes),
    text: header + body,
  };
}

async function main() {
  const args = process.argv.slice(2).filter((arg) => arg !== "--");
  if (args.length !== 1 || !["--write", "--check"].includes(args[0])) {
    throw new Error("usage: derive-worker-dark-source.mjs --write|--check");
  }
  const { text } = await deriveDarkSource();
  const target = join(root, DERIVED_SOURCE);
  if (args[0] === "--write") {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, text);
    console.log(`wrote ${DERIVED_SOURCE} (${sha256(text)})`);
    return;
  }
  const committed = await readFile(target, "utf8").catch(() => null);
  if (committed !== text) {
    console.error(`${DERIVED_SOURCE} differs from a fresh derivation`);
    process.exitCode = 1;
    return;
  }
  console.log(`${DERIVED_SOURCE} matches a fresh derivation (${sha256(text)})`);
}

if (
  process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await main();
}
