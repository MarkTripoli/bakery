/* Pure logo selection: no asset imports, so Node can import it (erasable
   TypeScript only; the JSON table is generated by brand/scripts/tables.mjs
   from assets/brand/logo/variants.json). `logo-assets.ts` binds the returned
   `file` to a bundled URL. */
import table from "./logo-table.json" with { type: "json" };
import type { LogoVariantId } from "./tokens.ts";

export type { LogoVariantId } from "./tokens.ts";
export type LogoSurfaceId = keyof typeof table.surfaces;
export type LogoArt = "mark" | "lockup" | "wordmark";
export type LogoTileVariantId = "tile-light" | "tile-dark";
export type LogoRequest =
  | {
    art: "mark";
    variant?: LogoVariantId;
    surface?: LogoSurfaceId;
    size?: number;
  }
  | {
    art: "lockup" | "wordmark";
    variant?: Exclude<LogoVariantId, LogoTileVariantId>;
    surface?: LogoSurfaceId;
    size?: number;
  };
export type LogoSelection = {
  /** Repo-relative path of the chosen SVG, a key of the URL table. */
  file: string;
  alt: "Bakery";
  variant: LogoVariantId;
  width: number;
  height: number;
  minSize: number;
};

export const DEFAULT_LOGO_VARIANT: LogoVariantId = "color-light";

type VariantRow = {
  files: Record<string, string | undefined>;
  dimensions: Record<string, { width: number; height: number } | undefined>;
};
const variants: Record<string, VariantRow> = table.variants;
const recommended: Record<string, string | undefined> = table.recommended;
const sizeRules: { minPx?: number; maxPx?: number; file: string }[] =
  table.sizeRules;

export const logoVariantIds = Object.keys(table.variants) as LogoVariantId[];
export const logoSurfaceIds = Object.keys(table.surfaces) as LogoSurfaceId[];
export type LogoSurface = {
  token: string;
  theme: string;
  hex: string;
  label: string;
};
/** Token surfaces a logo sits on: foundation token, theme and its hex. */
export const logoSurfaces: Record<LogoSurfaceId, LogoSurface> = table.surfaces;
export const recommendedVariant = (surface: LogoSurfaceId): LogoVariantId =>
  (recommended[surface] ?? DEFAULT_LOGO_VARIANT) as LogoVariantId;
/** Every distinct file the table can return (wordmarks are shared across variants). */
export const logoFiles = (): string[] => [
  ...new Set(
    Object.values(variants).flatMap((row) =>
      Object.values(row.files).filter((file) => file !== undefined)
    ),
  ),
];

function markKey(size: number | undefined): "mark" | "mark16" | "mark32" {
  if (size === undefined) return "mark";
  for (const rule of sizeRules) {
    const above = rule.minPx === undefined || size >= rule.minPx;
    const below = rule.maxPx === undefined || size <= rule.maxPx;
    if (above && below) return rule.file as "mark" | "mark16" | "mark32";
  }
  return "mark";
}

const round = (value: number) => Math.round(value * 10) / 10;

/** variant wins; else the surface's recommended variant; else color-light. */
export function selectLogo(request: LogoRequest): LogoSelection {
  const variant = (request.variant ??
    (request.surface ? recommended[request.surface] : undefined) ??
    DEFAULT_LOGO_VARIANT) as LogoVariantId;
  const row = variants[variant];
  if (!row) throw new Error(`logo: unknown variant "${variant}"`);
  const key = request.art === "mark" ? markKey(request.size) : request.art;
  const file = row.files[key];
  const natural = row.dimensions[key];
  if (!file || !natural) {
    throw new Error(`logo: variant "${variant}" has no ${request.art}`);
  }
  const { size } = request;
  const height = size === undefined ? natural.height : size;
  const width = size === undefined
    ? natural.width
    : round(size * natural.width / natural.height);
  const minSize = request.art === "mark"
    ? table.minSize.mark
    : request.art === "lockup"
    ? table.minSize.lockupHeight
    : table.minSize.wordmarkHeight;
  return { file, alt: "Bakery", variant, width, height, minSize };
}
