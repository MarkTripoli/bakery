/* Pure scene selection: no asset imports, so Node can import it. The JSON
   table is generated by brand/scripts/tables.mjs from
   assets/brand/scenes/scenes.json. `scene-assets.ts` binds `files` to URLs. */
import table from "./scene-table.json" with { type: "json" };

export type SceneId = keyof typeof table.scenes;
export type SceneTheme = "light" | "dark";
export type SceneOptions = { theme: SceneTheme; width?: 600 | 1200 };
export type SceneSelection = {
  /** Repo-relative path of the 600 px and 1200 px WebP, keys of the URL table. */
  file: string;
  files: { 600: string; 1200: string };
  width: number;
  height: number;
  alt: string;
};

type SceneRow = {
  alt: string;
  exports: Record<string, { width: number; height: number } | undefined>;
};
const scenes: Record<string, SceneRow> = table.scenes;

export const sceneIds = Object.keys(table.scenes) as SceneId[];
export const sceneFiles = (): string[] =>
  Object.entries(scenes).flatMap(([id, row]) =>
    Object.keys(row.exports).map((name) => `assets/brand/scenes/${id}/${name}`)
  );

export function selectScene(
  id: SceneId,
  options: SceneOptions,
): SceneSelection {
  const row = scenes[id];
  if (!row) throw new Error(`scene: unknown id "${id}"`);
  const path = (suffix: string) =>
    `assets/brand/scenes/${id}/${id}-${options.theme}${suffix}.webp`;
  const files = { 600: path("-600"), 1200: path("") };
  const file = files[options.width ?? 1200];
  const size = row.exports[file.slice(file.lastIndexOf("/") + 1)];
  if (!size) throw new Error(`scene: "${id}" has no ${file}`);
  return { file, files, width: size.width, height: size.height, alt: row.alt };
}
