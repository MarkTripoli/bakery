export type SceneAsset = Pick<SceneSelection, "width" | "height" | "alt"> & {
  src: string;
  srcSet: string;
};

/** Bundled scene art for a theme; `srcSet` offers the 600 and 1200 px WebP. */
export function scene(id: SceneId, options: SceneOptions): SceneAsset {
  const { file, files, width, height, alt } = selectScene(id, options);
  const url = (path: string) => {
    const found = urls[path];
    if (found === undefined) {
      throw new Error(`scene: no bundled URL for ${path}`);
    }
    return found;
  };
  return {
    src: url(file),
    srcSet: `${url(files[600])} 600w, ${url(files[1200])} 1200w`,
    width,
    height,
    alt,
  };
}
