import IntlMessageFormat from "intl-messageformat";
import { supportedLocales } from "../src/locale.ts";
import { minimumPseudoLength } from "./pseudo.ts";

const root = decodeURIComponent(new URL("..", import.meta.url).pathname);
const namespacePrefixes = [
  "auth.",
  "artifact.",
  "core.actions.",
  "core.pagination.",
  "shell.navigation.",
  "shell.health.",
  "shell.states.",
  "problems.",
  "projects.onboarding.",
  "projects.roles.",
  "tasks.",
  "workerEnrollment.",
  "workerList.",
  "workerDetail.",
  "settings.",
  "profile.",
  "preferences.",
  "passkeys.",
  "clients.",
  "oauth.",
  "organizationSettings.",
  "features.",
  "access.",
  "machines.",
  "repository.rules.",
] as const;

/**
 * Namespaces whose pseudo rows must be generated by `scripts/pseudo.ts`:
 * en-XA at least 35% longer than English, ar-XB RTL-wrapped. Older
 * namespaces predate the generator and are not held to the expansion rule.
 */
const pseudoExpansionPrefixes = [
  "tasks.run.",
  "tasks.conversation.",
  "artifact.",
  "settings.",
  "profile.",
  "preferences.",
  "passkeys.",
  "clients.",
  "oauth.",
  "organizationSettings.",
  "features.",
  "access.",
  "shell.navigation.machines",
  "machines.",
  "repository.rules.",
] as const;

function argumentNames(message: string): string[] {
  return [...message.matchAll(/\{\s*([A-Za-z][A-Za-z0-9_]*)\s*(?:,|\})/g)]
    .map((match) => match[1])
    .filter((value, index, values) => values.indexOf(value) === index)
    .sort();
}

function rawKeys(source: string): string[] {
  return [...source.matchAll(/"([^"\\]+)"\s*:/g)].map((match) => match[1]);
}

export function validateCatalogSources(
  sources: Readonly<Record<string, string>>,
): string[] {
  const errors: string[] = [];
  const parsed = new Map<string, Record<string, unknown>>();
  for (const [locale, source] of Object.entries(sources)) {
    try {
      if (new Intl.Locale(locale).toString() !== locale) {
        errors.push(`${locale}: catalog name must be canonical BCP 47`);
      }
    } catch {
      errors.push(`${locale}: catalog name must be valid BCP 47`);
    }
    const keys = rawKeys(source);
    const duplicateKeys = keys.filter((key, index) =>
      keys.indexOf(key) !== index
    );
    for (const key of new Set(duplicateKeys)) {
      errors.push(`${locale}: duplicate key ${key}`);
    }
    try {
      const value = JSON.parse(source);
      if (!value || typeof value !== "object" || Array.isArray(value)) {
        errors.push(`${locale}: catalog must be a flat JSON object`);
      } else {
        parsed.set(locale, value);
      }
    } catch (cause) {
      errors.push(
        `${locale}: invalid JSON (${
          cause instanceof Error ? cause.message : cause
        })`,
      );
    }
  }

  const english = parsed.get("en") ?? {};
  const englishKeys = Object.keys(english).sort();
  for (const key of englishKeys) {
    if (!namespacePrefixes.some((prefix) => key.startsWith(prefix))) {
      errors.push(`en: namespace escape ${key}`);
    }
    const message = english[key];
    if (typeof message !== "string") {
      errors.push(`en: ${key} must be a string`);
      continue;
    }
    if (/<\/?[A-Za-z][^>]*>/.test(message)) {
      errors.push(`en: unsafe rich tag in ${key}`);
    }
    try {
      new IntlMessageFormat(message, "en");
    } catch (cause) {
      errors.push(
        `en: invalid ICU message ${key} (${
          cause instanceof Error ? cause.message : cause
        })`,
      );
    }
  }

  for (const [locale, catalog] of parsed) {
    if (locale === "en") continue;
    for (const key of Object.keys(catalog).sort()) {
      if (!(key in english)) {
        errors.push(`${locale}: missing English key ${key}`);
      }
    }
    for (const key of englishKeys) {
      const message = catalog[key];
      if (typeof message !== "string") {
        errors.push(`${locale}: missing key ${key}`);
        continue;
      }
      if (/<\/?[A-Za-z][^>]*>/.test(message)) {
        errors.push(`${locale}: unsafe rich tag in ${key}`);
      }
      try {
        new IntlMessageFormat(message, locale);
      } catch (cause) {
        errors.push(
          `${locale}: invalid ICU message ${key} (${
            cause instanceof Error ? cause.message : cause
          })`,
        );
      }
      if (pseudoExpansionPrefixes.some((prefix) => key.startsWith(prefix))) {
        const source = String(english[key]);
        if (locale === "en-XA") {
          if (
            !message.startsWith("⟦") || !message.endsWith("⟧") ||
            message.length < minimumPseudoLength(source.length)
          ) {
            errors.push(
              `${locale}: ${key} must be ⟦…⟧ and at least 35% longer than English`,
            );
          }
        } else if (
          locale === "ar-XB" &&
          (!message.startsWith("⟪") || !message.endsWith("⟫"))
        ) {
          errors.push(`${locale}: ${key} must be wrapped in ⟪…⟫`);
        }
      }
      const expected = argumentNames(String(english[key]));
      const actual = argumentNames(message);
      if (expected.join("\n") !== actual.join("\n")) {
        errors.push(`${locale}: ICU argument drift in ${key}`);
      }
    }
  }
  return errors;
}

if (import.meta.main) {
  const sources: Record<string, string> = {};
  for (const locale of supportedLocales) {
    sources[locale] = await Deno.readTextFile(`${root}locales/${locale}.json`);
  }
  const errors = validateCatalogSources(sources);
  if (errors.length) throw new Error(errors.join("\n"));
  console.log(`Validated ${supportedLocales.length} locale catalogs.`);
}
