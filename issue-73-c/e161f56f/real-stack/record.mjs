import { createRequire } from "node:module";
import { execSync } from "node:child_process";
import { writeFileSync, mkdirSync } from "node:fs";
const require = createRequire("/home/marktripoli/Development/bakery-wt/rig-73-c/apps/web/package.json");
const { chromium } = require("@playwright/test");
const base = "http://127.0.0.1:41881";
const out = "/home/marktripoli/Development/bakery-wt/_notes/pr996-999-stills/stack73c/rec";
mkdirSync(out, { recursive: true });
const log = [];
const t0 = Date.now();
const note = (event, extra = {}) => log.push({ at: ((Date.now() - t0) / 1000).toFixed(1), event, ...extra });
const browser = await chromium.launch();
const signin = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const sp = await signin.newPage();
await sp.goto(base + "/sign-in");
await sp.getByLabel("Email").fill("ben@example.test");
await sp.getByLabel("Password", { exact: true }).fill("Owner-Passw0rd-Seed-1");
await sp.getByRole("button", { name: "Sign in", exact: true }).click();
await sp.waitForURL((url) => !url.pathname.startsWith("/sign-in"), { timeout: 30000 });
const state = await signin.storageState();
await signin.close();
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, storageState: state, recordVideo: { dir: out, size: { width: 1440, height: 900 } } });
const page = await context.newPage();
page.on("response", async (response) => {
  const request = response.request();
  const url = new URL(response.url());
  if (request.method() === "PATCH" && /\/notifications\//.test(url.pathname)) note("notification marked read", { status: response.status(), sent: request.postData() });
  if (/\/notifications\/[0-9a-f-]{36}\/target$/.test(url.pathname)) note("target resolved", { status: response.status(), body: (await response.text()).slice(0, 260) });
});
const rows = page.locator("[data-ui-component=notificationRow]");
await page.goto(base + "/notifications");
await rows.first().waitFor({ timeout: 30000 });
await page.waitForTimeout(1200);
note("inbox", { rows: await rows.count(), first: (await rows.first().innerText()).replace(/\s+/g, " ").slice(0, 120) });
await page.screenshot({ path: out + "/1-inbox.png" });
await rows.first().getByRole("link").first().click();
await page.locator("[data-landed='true']").first().waitFor({ timeout: 30000 });
note("landed", { path: new URL(page.url()).pathname, search: new URL(page.url()).search, outlined: (await page.locator("[data-landed='true']").first().innerText()).replace(/\s+/g, " ").slice(0, 140), taskChrome: await page.getByRole("link", { name: "Open task" }).count() });
await page.waitForTimeout(2500);
await page.screenshot({ path: out + "/2-landed.png" });
await page.goBack();
await rows.first().waitFor({ timeout: 30000 });
await page.waitForTimeout(1800);
note("back on inbox", { path: new URL(page.url()).pathname });
await page.screenshot({ path: out + "/3-back.png" });
execSync("docker exec dw73c-pg psql -h 127.0.0.1 -U postgres -d bakery -Atqc \"update bakery.artifact_access_grants set revoked_at = now(), revoked_by = 'e0acd075-01f2-4783-9906-b65a62e71b19' where artifact_id = 'be000000-0000-4000-8000-000000000020'\"");
note("grant revoked");
await page.waitForTimeout(600);
await rows.nth(1).getByRole("link").first().click({ timeout: 8000 });
const gone = page.locator("[data-testid^='shared-unavailable-']");
await gone.waitFor({ timeout: 30000 });
note("unavailable", { testid: await gone.getAttribute("data-testid"), text: (await gone.innerText()).replace(/\s+/g, " ").slice(0, 200), url: new URL(page.url()).pathname + new URL(page.url()).search });
await page.waitForTimeout(2500);
await page.screenshot({ path: out + "/4-unavailable.png" });
await page.getByRole("button", { name: "Back to notifications" }).click();
await rows.first().waitFor({ timeout: 30000 });
await page.waitForTimeout(1500);
note("inbox after", { path: new URL(page.url()).pathname });
await page.screenshot({ path: out + "/5-inbox-after.png" });
const video = await page.video().path();
await context.close();
await browser.close();
writeFileSync(out + "/transcript.json", JSON.stringify(log, null, 2));
console.log(JSON.stringify({ video, log }, null, 2));
